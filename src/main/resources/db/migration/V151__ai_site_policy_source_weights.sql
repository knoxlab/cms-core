-- FR-AI-KB-042②：站点级「源优先级加权」权重
--
-- 需求：「跨源（CMS/DOC/PIM/DAM）结果融合必须采用 ADR-17 的加权 RRF
-- （**或站点配置的源优先级加权**），不得简单拼接」。
--
-- 核实后确认：这个"站点配置的源优先级"**没有配置位** ——
-- 现有 `AskSourceRouter` 的候选顺序是**代码里的策略**（按问题类型推导），
-- 站点改不了；因此"或站点配置的源优先级加权"这条**无从表达**。
--
-- 用**单列 JSON** 而不是四列：
--   ① 来源域集合会变（DOC 是第 18 轮才加的），四列意味着每加一个来源就要迁移一次；
--   ② 权重是**一个整体**（相对大小才有意义），拆成四列会让"只改了其中一列"
--      成为一个数据上合法但语义可疑的状态。
--
-- 可空（null = 全部用内置默认）：权重是**调参**不是授权，
-- 缺省应当给出可用行为，而不是让融合整体不可用。
-- （与 FR-AI-KB-057 的出域开关刻意不同 —— 那是授权，缺省必须 fail-closed。）
--
-- 格式与校验在 `SourceWeightConfig` 里：未知来源键、非有限数、负数、
-- 全零都会报错，**不静默忽略**（静默忽略会让站点以为自己配的权重生效了）。
alter table ai_site_policy add column source_weights varchar(500);
