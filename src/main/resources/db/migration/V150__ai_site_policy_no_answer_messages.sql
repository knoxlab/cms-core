-- FR-AI-KB-062：无答案话术的站点级可配置
--
-- 验收标准：「文档源无命中时必须返回既有固定话术（不生成内容），并区分
-- 「文档库为空/未索引」与「已索引但无相关内容」两种情形给出不同提示」，
-- 验收要点含「**话术可配置**」。
--
-- 第 16 轮已把两种情形拆成两个具名常量（`NO_ANSWER_MESSAGE` /
-- `EMPTY_LIBRARY_MESSAGE`）并接入判定，但话术**仍是硬编码常量** ——
-- 站点无法按自己的措辞与品牌表达调整，也无法补上"去哪里导入文档"这类
-- 只有站点自己知道的信息。
--
-- 两列都可空，语义与既有 `monthly_token_quota`（DEF-AI-04）一致：
--   null/空串 = 使用内置默认话术
--   非空      = 站点自定义话术
--
-- 为什么用「空即默认」而不是写入默认值：默认话术会随产品迭代调整措辞，
-- 若在迁移时把当时的默认值**固化成每个站点的数据**，那些站点将永远拿不到
-- 后续的措辞改进，而运维面看起来"配置得好好的"，无从发现。
--
-- 为什么单列存提示语而不是存模板：它是一句给最终用户看的话，
-- 模板化会引入占位符替换与转义问题，而收益只是省几个字的重复。
alter table ai_site_policy add column no_answer_message varchar(500);
alter table ai_site_policy add column empty_library_message varchar(500);
