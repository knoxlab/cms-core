-- OBS-11-10：版本行显式记录「来源版本」，恢复（FR-CV-VER-004）产生的版本才有值。
--
-- 背景：恢复采用「以目标版本快照创建新版本」语义后，新版本的备注只写「恢复到 v{n}」文案，
-- 版本号本身无法机器判定来源；界面默认对比区间只能退化为「上一版本 → 最新版本」，
-- 恢复场景下会把「恢复动作前的版本」当作对比基线，看不出本次恢复究竟还原了哪些字段。
--
-- 口径：仅「恢复到 v{n}」写入 reverted_from = n（n 必须小于本行 version）；人工保存、AI 采纳
-- 版本保持 NULL，其对比基线仍为上一版本。
ALTER TABLE content_version
    ADD COLUMN reverted_from INTEGER;

